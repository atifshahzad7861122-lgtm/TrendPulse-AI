@router.get("/usage", response_model=List[LLMUsageRecord])
def list_llm_usage(
    provider: Optional[str] = Query(None),
    request_type: Optional[str] = Query(None),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    current_user: User = Depends(get_current_user),
    usage_repo: LLMUsageRepository = Depends(get_llm_usage_repository)
):
    """
    Retrieves telemetry usage records for the current user/workspace.
    """
    return usage_repo.list_usage(
        user_id=current_user.id,
        workspace_id=getattr(current_user, "workspace_id", None) or "ws_default",
        provider=provider,
        request_type=request_type,
        limit=limit,
        offset=offset
    )


@router.get("/usage/summary", response_model=LLMUsageSummaryResponse)
def get_llm_usage_summary(
    current_user: User = Depends(get_current_user),
    usage_repo: LLMUsageRepository = Depends(get_llm_usage_repository)
):
    """
    Returns aggregated token consumption and estimated cost summaries.
    """
    summary = usage_repo.get_summary(
        user_id=current_user.id,
        workspace_id=getattr(current_user, "workspace_id", None) or "ws_default"
    )
    return LLMUsageSummaryResponse(**summary)
